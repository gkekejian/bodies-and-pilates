import type { Metadata, Viewport } from "next";
import { Fraunces, Montserrat, Poppins } from "next/font/google";
import "./globals.css";
import { Header } from "@/components/layout/header";
import { Footer } from "@/components/layout/footer";
import { MobileBookingBar } from "@/components/layout/mobile-booking-bar";
import CookieBanner from "@/components/analytics/cookie-banner";
import Analytics from "@/components/analytics/analytics";
import { exerciseGymSchema, websiteSchema, jsonLd } from "@/lib/schema";
import { SITE_NAME, SITE_URL } from "@/lib/site";

// Type system from the old site. Only the display serif (the hero headline,
// the LCP text) is preloaded; the others swap in when first used. The theme's
// paragraph font, Times New Roman, is a system font (--font-accent, globals.css).
const display = Fraunces({
  subsets: ["latin"],
  variable: "--font-display",
  display: "swap",
  // Variable font with the optical-size axis, pinned at 120 in globals.css
  // (the Wix editor's "Fraunces 120 Semi Bold").
  axes: ["opsz"],
});

const sans = Montserrat({
  subsets: ["latin"],
  variable: "--font-sans",
  display: "swap",
  weight: ["400", "500"],
  preload: false,
});

const light = Poppins({
  subsets: ["latin"],
  variable: "--font-light",
  display: "swap",
  weight: ["200", "300"],
  preload: false,
});

// Defaults only. Every page sets its own title, description, canonical, and
// Open Graph tags via pageMetadata() in lib/metadata.ts. The share image is
// generated by app/opengraph-image.tsx.
export const metadata: Metadata = {
  metadataBase: new URL(SITE_URL),
  title: {
    template: `%s | ${SITE_NAME}`,
    default: "Pilates Studio in North Hollywood | Bodies and Pilates",
  },
  openGraph: {
    type: "website",
    locale: "en_US",
    siteName: SITE_NAME,
  },
  twitter: { card: "summary_large_image" },
  robots: { index: true, follow: true },
};

export const viewport: Viewport = {
  themeColor: "#534745",
};

export default function RootLayout({ children }: { children: React.ReactNode }) {
  return (
    <html lang="en" className={`${display.variable} ${sans.variable} ${light.variable}`} suppressHydrationWarning>
      <head>
        <script
          type="application/ld+json"
          dangerouslySetInnerHTML={{ __html: jsonLd(exerciseGymSchema) }}
        />
        <script type="application/ld+json" dangerouslySetInnerHTML={{ __html: jsonLd(websiteSchema) }} />
      </head>
      <body className="flex min-h-screen flex-col pb-[calc(4.5rem+env(safe-area-inset-bottom))] md:pb-0">
        <a
          href="#main"
          className="sr-only z-[60] rounded bg-charcoal-900 px-4 py-2 font-sans text-sm text-cream-50 focus:not-sr-only focus:fixed focus:left-4 focus:top-4"
        >
          Skip to content
        </a>
        <Header />
        <main id="main" tabIndex={-1} className="flex-1 focus:outline-none">
          {children}
        </main>
        <Footer />
        <MobileBookingBar />
        <CookieBanner />
        <Analytics />
      </body>
    </html>
  );
}
